def test_structural_anomalies_are_reported(tmp_path: Path) -> None:
    prepare_document(tmp_path, page_count=1, table_count=1)
    candidate = make_candidate(
        tmp_path,
        index=1,
        dataframe=pd.DataFrame(
            [
                ["Indicateurs", "S1 2026"],
                ["", "181 466"],
                ["Exploita- tion", "22 985"],
            ]
        ),
    )

    report = ParserValidator().validate(
        output_dir=tmp_path,
        page_count=1,
        tables=[candidate],
    )
    codes = {issue.code for issue in report.tables[0].issues}

