import json
from pathlib import Path

import pandas as pd

from moroccan_markets_ai.data.parsers.parser_validator import (
    VALIDATION_SCHEMA_VERSION,
    ParserStatus,
    ParserValidator,
    TableCandidate,
    is_cache_valid,
)


def prepare_document(
    output_dir: Path,
    *,
    page_count: int,
    table_count: int,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "tables").mkdir()
    (output_dir / "document.md").write_text(
        "# Document de test\n",
        encoding="utf-8",
    )
    (output_dir / "document.json").write_text(
        json.dumps(
            {
                "pages": {
                    str(page): {"page_no": page}
                    for page in range(1, page_count + 1)
                },
                "tables": [{} for _ in range(table_count)],
            }
        ),
        encoding="utf-8",
    )


def make_candidate(
    output_dir: Path,
    *,
    index: int,
    dataframe: pd.DataFrame,
    pages: list[int] | None = None,
) -> TableCandidate:
    csv_path = output_dir / "tables" / f"table_{index:03d}.csv"
    dataframe.to_csv(csv_path, index=False)
    return TableCandidate(
        table_index=index,
        pages=pages or [1],
        dataframe=dataframe,
        csv_path=csv_path,
    )


def test_valid_document_is_parsed(tmp_path: Path) -> None:
    prepare_document(tmp_path, page_count=1, table_count=1)
    candidate = make_candidate(
        tmp_path,
        index=1,
        dataframe=pd.DataFrame(
            {
                "Indicateur": ["Chiffre d'affaires"],
                "S1 2026": ["181 466"],
            }
        ),
    )

    report = ParserValidator().validate(
        output_dir=tmp_path,
        page_count=1,
        tables=[candidate],
    )

    assert report.status == ParserStatus.PARSED
    assert report.valid_table_count == 1
    assert report.invalid_table_count == 0
    assert not report.issues
    assert set(report.artifact_sha256) == {
        "document.md",
        "document.json",
        "tables/table_001.csv",
    }


def test_empty_table_is_partial_when_another_table_is_valid(
    tmp_path: Path,
) -> None:
    prepare_document(tmp_path, page_count=2, table_count=2)
    valid = make_candidate(
        tmp_path,
        index=1,
        dataframe=pd.DataFrame({"Libellé": ["Résultat net"]}),
    )
    empty = make_candidate(
        tmp_path,
        index=2,
        dataframe=pd.DataFrame(),
        pages=[2],
    )

    report = ParserValidator().validate(
        output_dir=tmp_path,
        page_count=2,
        tables=[valid, empty],
    )

    assert report.status == ParserStatus.PARTIAL
    assert report.valid_table_count == 1
    assert report.invalid_table_count == 1
    assert report.ocr_required_pages == [2]
    assert report.ocr_required_table_indexes == [2]
    assert {issue.code for issue in report.tables[1].issues} >= {
        "EMPTY_TABLE",
        "IMAGE_TABLE_REQUIRES_OCR",
        "CSV_UNREADABLE",
    }


