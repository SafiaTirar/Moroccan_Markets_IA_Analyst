def test_cache_checks_hashes_and_exact_csv_set(tmp_path: Path) -> None:
    prepare_document(tmp_path, page_count=1, table_count=1)
    candidate = make_candidate(
        tmp_path,
        index=1,
        dataframe=pd.DataFrame({"Indicateur": ["Résultat net"]}),
    )
    report = ParserValidator().validate(
        output_dir=tmp_path,
        page_count=1,
        tables=[candidate],
    )
    metadata = {
        "sha256": "source-hash",
        "docling_version": "2.140.0",
        "validation_schema_version": VALIDATION_SCHEMA_VERSION,
        "status": "PARSED",
        "table_count": 1,
        "validation": report.model_dump(mode="json"),
        "backend": "backend-a",
        "extraction_config_sha256": "config-a",
    }

    assert is_cache_valid(
        output_dir=tmp_path,
        metadata=metadata,
        source_sha256="source-hash",
        docling_version="2.140.0",
        backend_name="backend-a",
        extraction_config_sha256="config-a",
    )

    (tmp_path / "tables" / "table_002.csv").write_text(
        "stale\n",
        encoding="utf-8",
    )
    assert not is_cache_valid(
        output_dir=tmp_path,
        metadata=metadata,
        source_sha256="source-hash",
        docling_version="2.140.0",
        backend_name="backend-a",
        extraction_config_sha256="config-a",
    )

    (tmp_path / "tables" / "table_002.csv").unlink()
    (tmp_path / "tables" / "table_001.csv").write_text(
        "corrompu\n",
        encoding="utf-8",
    )
    assert not is_cache_valid(
        output_dir=tmp_path,
        metadata=metadata,
        source_sha256="source-hash",
        docling_version="2.140.0",
        backend_name="backend-a",
        extraction_config_sha256="config-a",
    )


